create extension if not exists pg_cron with schema pg_catalog;

create table if not exists public.kabirui_feedback (
    id uuid primary key default gen_random_uuid(),
    kind text not null check (kind in ('rating', 'bug')),
    rating smallint,
    message text,
    steps text,
    app_version text not null default 'unknown',
    locale text not null default 'unknown',
    submitted_at timestamptz not null default now(),
    constraint kabirui_feedback_version_length check (char_length(app_version) <= 32),
    constraint kabirui_feedback_locale_length check (char_length(locale) <= 64),
    constraint kabirui_feedback_payload check (
        (kind = 'rating'
            and rating is not null
            and rating between 1 and 5
            and (message is null or char_length(message) <= 1200)
            and steps is null)
        or
        (kind = 'bug'
            and rating is null
            and message is not null
            and char_length(btrim(message)) between 1 and 2000
            and (steps is null or char_length(steps) <= 2000))
    )
);

create table if not exists public.kabirui_feedback_rate_limit (
    id bigint generated by default as identity primary key,
    rate_key_hash text not null check (rate_key_hash ~ '^[a-f0-9]{64}$'),
    submitted_at timestamptz not null default now()
);

create index if not exists kabirui_feedback_rate_limit_key_time_idx
    on public.kabirui_feedback_rate_limit(rate_key_hash, submitted_at desc);

alter table public.kabirui_feedback enable row level security;
alter table public.kabirui_feedback_rate_limit enable row level security;
revoke all on table public.kabirui_feedback from public, anon, authenticated, service_role;
revoke all on table public.kabirui_feedback_rate_limit from public, anon, authenticated, service_role;

create or replace function public.submit_kabirui_feedback(
    p_kind text,
    p_rating integer,
    p_message text,
    p_steps text,
    p_app_version text,
    p_locale text,
    p_rate_key_hash text
) returns text
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $function$
declare
    v_submission_count integer;
    v_oldest_submission timestamptz;
    v_retry_after integer;
    v_now timestamptz;
begin
    if p_kind is null or p_kind not in ('rating', 'bug')
        or p_app_version is null or char_length(p_app_version) > 32
        or p_locale is null or char_length(p_locale) > 64
        or p_rate_key_hash is null or p_rate_key_hash !~ '^[a-f0-9]{64}$' then
        raise exception using errcode = '22023', message = 'invalid_submission';
    end if;

    if p_kind = 'rating' then
        if p_rating is null or p_rating not between 1 and 5
            or (p_message is not null and char_length(p_message) > 1200)
            or p_steps is not null then
            raise exception using errcode = '22023', message = 'invalid_submission';
        end if;
    elsif p_rating is not null
        or p_message is null
        or char_length(btrim(p_message)) not between 1 and 2000
        or (p_steps is not null and char_length(p_steps) > 2000) then
        raise exception using errcode = '22023', message = 'invalid_submission';
    end if;

    perform pg_advisory_xact_lock(hashtextextended(p_rate_key_hash, 0));
    v_now := clock_timestamp();

    delete from public.kabirui_feedback_rate_limit
    where submitted_at < v_now - interval '2 hours';

    select count(*)::integer, min(submitted_at)
    into v_submission_count, v_oldest_submission
    from public.kabirui_feedback_rate_limit
    where rate_key_hash = p_rate_key_hash
      and submitted_at > v_now - interval '1 hour';

    if v_submission_count >= 5 then
        v_retry_after := greatest(
            1,
            ceil(extract(epoch from (v_oldest_submission + interval '1 hour' - v_now)))::integer
        );
        return 'rate_limited:' || v_retry_after::text;
    end if;

    insert into public.kabirui_feedback_rate_limit(rate_key_hash, submitted_at)
    values (p_rate_key_hash, v_now);

    insert into public.kabirui_feedback(kind, rating, message, steps, app_version, locale)
    values (p_kind, p_rating::smallint, nullif(btrim(p_message), ''), nullif(btrim(p_steps), ''), p_app_version, p_locale);

    return 'accepted';
end;
$function$;

revoke all on function public.submit_kabirui_feedback(text, integer, text, text, text, text, text) from public, anon, authenticated;
grant execute on function public.submit_kabirui_feedback(text, integer, text, text, text, text, text) to service_role;

do $schedule$
begin
    if not exists (select 1 from cron.job where jobname = 'kabirui-feedback-retention') then
        perform cron.schedule(
            'kabirui-feedback-retention',
            '17 * * * *',
            $command$delete from public.kabirui_feedback where submitted_at < now() - interval '12 months';$command$
        );
    end if;
    if not exists (select 1 from cron.job where jobname = 'kabirui-feedback-rate-cleanup') then
        perform cron.schedule(
            'kabirui-feedback-rate-cleanup',
            '*/10 * * * *',
            $command$delete from public.kabirui_feedback_rate_limit where submitted_at < now() - interval '2 hours';$command$
        );
    end if;
end;
$schedule$;

